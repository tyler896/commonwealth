def upsert_products(products, line_name, line_key)
  store = Spree::Store.default
  channel = Spree::Channel.find_by(code: 'online') || Spree::Channel.first
  shipping = Spree::ShippingCategory.first || Spree::ShippingCategory.create!(name: 'Default')
  stock = Spree::StockLocation.first

  created = 0
  updated = 0

  products.each do |attrs|
    product = Spree::Product.find_by(slug: attrs[:slug]) || Spree::Product.new(slug: attrs[:slug])
    is_new = product.new_record?

    product.assign_attributes(
      name: attrs[:name],
      description: "#{attrs[:description]}\n\nLineage: #{attrs[:lineage]}\nLine: #{line_name}\nPack: 3-pack feminized\nBrand: Commonwealth Seed Co",
      status: 'active',
      store: store,
      shipping_category: shipping,
      meta_title: "#{attrs[:name]} | Commonwealth Seed Co",
      meta_description: "#{attrs[:lineage]} feminized seeds from Commonwealth Seed Co."
    )
    product.price = attrs[:price]
    product.metadata = {
      'lineage' => attrs[:lineage],
      'line' => line_key,
      'pack_size' => '3-pack',
      'brand' => 'Commonwealth Seed Co',
      'featured' => attrs[:featured],
      'coming_soon' => true
    }
    product.save!

    product.master.update!(sku: attrs[:sku])
    product.channels = [channel] if channel

    if product.respond_to?(:product_publications) && channel
      pub = product.product_publications.find_or_initialize_by(channel: channel)
      pub.published_at ||= Time.current
      pub.save!
    end

    if stock
      si = product.master.stock_items.find_or_initialize_by(stock_location: stock)
      si.count_on_hand = 25
      si.backorderable = true
      si.save!
    end

    is_new ? created += 1 : updated += 1
    puts "#{is_new ? 'CREATED' : 'UPDATED'} #{product.slug} [#{line_key}] (#{product.id})"
  end

  [created, updated]
end

wt_c, wt_u = upsert_products(wild_thornberry, 'Wild Thornberry', 'wild-thornberry')
gs_c, gs_u = upsert_products(grape_sunshine, 'Grape Sunshine', 'grape-sunshine')

puts "Wild Thornberry: created=#{wt_c} updated=#{wt_u}"
puts "Grape Sunshine: created=#{gs_c} updated=#{gs_u}"
puts "Done. total=#{Spree::Product.count}"
